// 将并行预计算的分片合并为浏览器直接加载的静态结果。
const fs = require('fs');
const path = require('path');

const projectDir = __dirname;
const shardCount = Number(process.argv[2] || 1);
const outputPath = path.join(projectDir, 'city_extremes_results.js');
const output = {};
if (fs.existsSync(outputPath)) {
    const existingCode = fs.readFileSync(outputPath, 'utf8');
    const startMarker = 'window.cityExtremeResults = ';
    const start = existingCode.indexOf(startMarker);
    if (start !== -1) {
        const jsonStart = start + startMarker.length;
        const jsonEnd = existingCode.lastIndexOf(';');
        Object.assign(output, JSON.parse(existingCode.slice(jsonStart, jsonEnd)));
    }
}
for (let shard = 0; shard < shardCount; shard++) {
    const shardData = JSON.parse(fs.readFileSync(path.join(projectDir, `city_extremes_results_${shard}.json`), 'utf8'));
    for (const [cityKey, cityResults] of Object.entries(shardData)) {
        output[cityKey] = { ...(output[cityKey] || {}), ...cityResults };
    }
}
fs.writeFileSync(
    outputPath,
    `// Generated by precompute_city_extremes.js. Do not edit manually.\nwindow.cityExtremeResults = ${JSON.stringify(output)};\n`
);
console.log(`Merged ${Object.keys(output).length} cities into city_extremes_results.js`);
